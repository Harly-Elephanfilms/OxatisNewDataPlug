export default function Sidebar() {
  const pathname = usePathname();
  const [open, setOpen] = useState(false);

  // Close drawer on route change
  useEffect(() => {
    setOpen(false);
  }, [pathname]);

  // Close on Escape key
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") setOpen(false); };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, []);

  const isActive = (href: string) => {
    if (href === "/") return pathname === "/";
    return pathname.startsWith(href);
  };

  const currentPage = navItems.find((item) => isActive(item.href));

  return (
    <>
      {/* ── Top bar ─────────────────────────────────────────────── */}
      <header className="app-topbar">
        {/* Burger */}
        <button
          onClick={() => setOpen(true)}
          className="topbar-burger"
          aria-label="Ouvrir le menu"
        >
          <span className="burger-line" />
          <span className="burger-line" />
          <span className="burger-line" />
        </button>

        {/* Brand */}
        <div className="topbar-brand">
          <div className="topbar-brand-icon">
            <svg className="w-4 h-4 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 3v11.25A2.25 2.25 0 006 16.5h2.25M3.75 3h-1.5m1.5 0h16.5m0 0h1.5m-1.5 0v11.25A2.25 2.25 0 0118 16.5h-2.25m-7.5 0h7.5m-7.5 0l-1 3m8.5-3l1 3m0 0l.5 1.5m-.5-1.5h-9.5m0 0l-.5 1.5M9 11.25v1.5M12 9v3.75m3-6v6" />
            </svg>
          </div>
          <div>
            <span className="topbar-brand-name">Elephant Films</span>
            <span className="topbar-brand-sub">Outils Oxatis</span>
          </div>
        </div>

        {/* Current page breadcrumb */}
        {currentPage && (
          <div className="topbar-page">
            <span className="topbar-page-icon">{currentPage.icon}</span>
            <span className="topbar-page-label">{currentPage.label}</span>
          </div>
        )}
      </header>

      {/* ── Backdrop ────────────────────────────────────────────── */}
      {open && (
        <div
          className="nav-overlay"
          onClick={() => setOpen(false)}
          aria-hidden="true"
        />
      )}

      {/* ── Drawer ──────────────────────────────────────────────── */}
      <nav className={`nav-drawer${open ? " nav-drawer-open" : ""}`} aria-label="Navigation principale">
        {/* Drawer header */}
        <div className="drawer-header">
          <div className="flex items-center gap-3">
            <div className="topbar-brand-icon">
              <svg className="w-4 h-4 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 3v11.25A2.25 2.25 0 006 16.5h2.25M3.75 3h-1.5m1.5 0h16.5m0 0h1.5m-1.5 0v11.25A2.25 2.25 0 0118 16.5h-2.25m-7.5 0h7.5m-7.5 0l-1 3m8.5-3l1 3m0 0l.5 1.5m-.5-1.5h-9.5m0 0l-.5 1.5M9 11.25v1.5M12 9v3.75m3-6v6" />
              </svg>
            </div>
            <div>
              <p className="text-white font-semibold text-sm leading-tight">Elephant Films</p>
              <p style={{ color: "#a5b4fc", fontSize: "0.7rem" }}>Outils Oxatis</p>
            </div>
          </div>
          <button
            onClick={() => setOpen(false)}
            className="drawer-close"
            aria-label="Fermer le menu"
          >
            <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Nav items */}
        <div className="drawer-nav">
          <p className="drawer-section-label">Navigation</p>
          <ul style={{ listStyle: "none", padding: 0, margin: 0, display: "flex", flexDirection: "column", gap: 2 }}>
            {navItems.map((item) => {
              const active = isActive(item.href);
              return (
                <li key={item.href}>
                  <Link
                    href={item.href}
                    style={{
                      display: "flex",
                      alignItems: "center",
                      gap: "0.625rem",
                      padding: "0.625rem 0.75rem",
                      borderRadius: "0.5rem",
                      fontSize: "0.9rem",
                      fontWeight: active ? 600 : 400,
                      textDecoration: "none",
                      color: active ? "#fff" : "#c7d2fe",
                      background: active ? "rgba(99,102,241,0.35)" : "transparent",
                      transition: "background 0.15s ease, color 0.15s ease",
                    }}
                    onMouseEnter={(e) => {
                      if (!active) {
                        (e.currentTarget as HTMLAnchorElement).style.background = "rgba(255,255,255,0.06)";
                        (e.currentTarget as HTMLAnchorElement).style.color = "#fff";
                      }
                    }}
                    onMouseLeave={(e) => {
                      if (!active) {
                        (e.currentTarget as HTMLAnchorElement).style.background = "transparent";
                        (e.currentTarget as HTMLAnchorElement).style.color = "#c7d2fe";
                      }
                    }}
                  >
                    <span style={{ color: active ? "#a5b4fc" : "#818cf8", flexShrink: 0, display: "flex" }}>
                      {item.icon}
                    </span>
                    {item.label}
                    {active && (
                      <span style={{ marginLeft: "auto", width: 6, height: 6, borderRadius: "50%", background: "#a5b4fc", flexShrink: 0 }} />
                    )}
                  </Link>
                </li>
              );
            })}
          </ul>
        </div>

        {/* Drawer footer */}
        <div className="drawer-footer">
          v1.0 — elephantfilms.com
        </div>
      </nav>
    </>
  );
}
